import re, glob, os

os.chdir(r'C:/Users/fr/AutoRepairOS')
files = sorted(glob.glob('web/pages/*_templ.go'))
funcs = []
for p in files:
    src = open(p, encoding='utf-8').read()
    for m in re.finditer(r'^func\s+([A-Z]\w*)\s*\(([^)]*)\)\s+templ\.Component', src, re.M | re.S):
        name, params = m.group(1), m.group(2)
        parts, depth, cur = [], 0, ''
        for ch in params:
            if ch in '[({':
                depth += 1
            elif ch in '])}':
                depth -= 1
            if ch == ',' and depth == 0:
                parts.append(cur); cur = ''
            else:
                cur += ch
        if cur.strip():
            parts.append(cur)
        args = []
        ok = True
        pending = []
        for pr in parts:
            pr = ' '.join(pr.split())
            if not pr:
                continue
            toks = pr.split()
            if len(toks) == 1 and re.match(r'^[a-z_]\w*$', toks[0]):
                pending.append(toks[0])
                continue
            if len(toks) >= 2 and re.match(r'^[a-z_]\w*$', toks[0]):
                pending.append(toks[0])
                typ = ' '.join(toks[1:])
                for _ in pending:
                    args.append(typ)
                pending = []
            else:
                args.append(pr)
            typ = args[-1]
            if typ.strip().startswith('...'):
                ok = False; break
        if pending:
            ok = False
        if ok:
            funcs.append((name, args))

INTERFACES = {'context.Context', 'io.Writer', 'templ.Component', 'http.ResponseWriter', 'error', 'interface{}', 'any'}
PRIMS = {'int': '0', 'int8': '0', 'int16': '0', 'int32': '0', 'int64': '0',
         'uint': '0', 'uint8': '0', 'uint16': '0', 'uint32': '0', 'uint64': '0',
         'float32': '0', 'float64': '0', 'byte': '0', 'rune': '0', 'string': '""', 'bool': 'false'}

def zero(t):
    t = t.strip()
    if t.startswith('[]') or t.startswith('map[') or t.startswith('*') or t.startswith('...'):
        return 'nil'
    if t in PRIMS:
        return PRIMS[t]
    if t in INTERFACES:
        return 'nil'
    if '.' in t:
        return t + '{}'
    return t + '{}'

