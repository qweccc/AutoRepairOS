package handler

import "testing"

// TestNormalizePhoneCases 獨立驗證台灣手機號碼正規化。
//
// 與 line_binding_test.go 分開放，因為該檔常與其他 LINE 相關變更同時被修改；
// 這裡只依賴 normalizePhone 的行為契約，衝突時更容易定位。
func TestNormalizePhoneCases(t *testing.T) {
	cases := []struct {
		in   string
		want string
	}{
		// 標準格式
		{"0912345678", "0912345678"},

		// 常見分隔符號
		{"0912-345-678", "0912345678"},
		{"0912 345 678", "0912345678"},
		{"0912.345.678", "0912345678"},

		// 帶國碼（+886 或 886 開頭，總共 12 碼）
		{"+886 912 345 678", "0912345678"},
		{"886912345678", "0912345678"},

		// 使用者在訊息中夾帶其他文字
		{"0912345678 請幫我查", "0912345678"},
		{"我的號碼是0912345678", "0912345678"},

		// 非手機號碼或格式不對 → 空字串
		{"進度", ""},
		{"", ""},
		{"123", ""},
		{"02-2345-6789", ""}, // 台北市號，不是手機
		{"09123456789", ""},  // 11 碼，過長
		{"1912345678", ""},   // 不是 09 開頭
		{"不確定", ""},
	}

	for _, c := range cases {
		got := normalizePhone(c.in)
		if got != c.want {
			t.Errorf("normalizePhone(%q) = %q, want %q", c.in, got, c.want)
		}
	}
}